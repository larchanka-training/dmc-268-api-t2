"""Pre-LLM input guards (dmc-268-ui-t2#33): skip files no review can use.

Checks run cheapest first: diff metadata, then path patterns, then the diff
text itself. No file content is downloaded. Every skip carries an enumerated
reason; the canonical context wire still reports ``policy``.

Migrations are reviewed by default (they change data and schema);
``exclude_migrations`` opts a repository out.
"""

from __future__ import annotations

from collections.abc import Iterable, Mapping
from enum import StrEnum
from pathlib import PurePosixPath
from typing import Any

from pydantic import BaseModel, ConfigDict, Field


class FileSkipReason(StrEnum):
    REMOVED = "removed"
    PURE_RENAME = "pure_rename"
    BINARY = "binary"
    TOO_LARGE = "too_large"
    IGNORED = "ignored"
    LOCKFILE = "lockfile"
    MIGRATION = "migration"
    GENERATED = "generated"
    BUNDLE = "bundle"
    VENDORED = "vendored"
    MINIFIED = "minified"
    # Incremental review: unchanged since a prior review of this PR.
    ALREADY_REVIEWED = "already_reviewed"


LOCKFILE_GLOBS = (
    "*.lock",
    "package-lock.json",
    "npm-shrinkwrap.json",
    "pnpm-lock.yaml",
    "go.sum",
    "packages.lock.json",
)
MIGRATION_GLOBS = (
    "migrations/**",
    "alembic/versions/**",
    "db/migrate/**",
)
GENERATED_GLOBS = (
    "*.pb.go",
    "*_pb2.py",
    "*_pb2_grpc.py",
    "*.pb.ts",
    "*.generated.*",
    "*.gen.go",
    "*.g.dart",
    "*.freezed.dart",
    "__generated__/**",
    "*.snap",
)
BUNDLE_GLOBS = (
    "dist/**",
    "build/**",
    "*.min.js",
    "*.min.css",
    "*.map",
    "*.bundle.js",
    "*.chunk.js",
)
VENDORED_GLOBS = ("vendor/**", "node_modules/**")
BINARY_EXTENSIONS = (
    # images
    ".png", ".jpg", ".jpeg", ".gif", ".bmp", ".ico", ".webp", ".tiff", ".psd",
    # fonts
    ".woff", ".woff2", ".ttf", ".otf", ".eot",
    # archives
    ".zip", ".tar", ".gz", ".tgz", ".bz2", ".xz", ".7z", ".rar", ".jar", ".war",
    # compiled
    ".wasm", ".so", ".dll", ".exe", ".dylib", ".a", ".o", ".class", ".pyc",
    # media and documents
    ".pdf", ".mp3", ".mp4", ".mov", ".avi", ".webm", ".sqlite",
)  # fmt: skip
GENERATED_MARKERS = (
    "@generated",
    "do not edit",
    "code generated by",
    "generated by",
    "autogenerated",
    "auto-generated",
)
# Markers count only on comment lines, so string literals never match.
_COMMENT_PREFIXES = ("#", "//", "/*", "*", "<!--", "--", ";")


class InputGuardPolicy(BaseModel):
    """Thresholds and patterns; defaults are overridable per deployment."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    max_patch_bytes: int = Field(default=1024 * 1024, ge=1)
    # Admission limits count kept files only; this bounds the parsing work.
    max_raw_files: int = Field(default=1000, ge=1)
    # Bounds glob matching for an oversized base-branch .gitattributes.
    max_linguist_rules: int = Field(default=1000, ge=0)
    exclude_migrations: bool = False
    include_globs: tuple[str, ...] = ()
    lockfile_globs: tuple[str, ...] = LOCKFILE_GLOBS
    migration_globs: tuple[str, ...] = MIGRATION_GLOBS
    generated_globs: tuple[str, ...] = GENERATED_GLOBS
    bundle_globs: tuple[str, ...] = BUNDLE_GLOBS
    vendored_globs: tuple[str, ...] = VENDORED_GLOBS
    binary_extensions: tuple[str, ...] = BINARY_EXTENSIONS
    content_probe_bytes: int = Field(default=8 * 1024, ge=1)
    generated_markers: tuple[str, ...] = GENERATED_MARKERS
    generated_header_lines: int = Field(default=10, ge=1)
    # A single line this long with almost no whitespace is minified output.
    minified_line_length: int = Field(default=500, ge=1)
    minified_max_whitespace_ratio: float = Field(default=0.05, ge=0, le=1)
    # Average added-line length above this marks the whole file as minified.
    minified_avg_line_length: int = Field(default=300, ge=1)
    # (pattern, attribute, is_set) from the base branch .gitattributes.
    linguist_rules: tuple[tuple[str, str, bool], ...] = ()

    def with_gitattributes(self, text: str | None) -> InputGuardPolicy:
        """Add ``linguist-generated`` / ``linguist-vendored`` rules, in file order."""
        rules: list[tuple[str, str, bool]] = []
        for line in (text or "").splitlines():
            if not line.strip() or line.lstrip().startswith("#"):
                continue
            pattern, *attributes = line.split()
            for attribute in attributes:
                name, _, value = attribute.lstrip("-!").partition("=")
                if name in _LINGUIST_REASONS:
                    is_set = not attribute.startswith(("-", "!")) and value != "false"
                    rules.append((pattern, name, is_set))
        kept = tuple(rules[: self.max_linguist_rules])
        return self.model_copy(update={"linguist_rules": kept})

    def for_repository(self, ignores: Mapping[str, Any]) -> InputGuardPolicy:
        """Apply frozen ``RepositorySettings.ignores`` overrides; ``globs`` stays
        the repository exclude list and is passed to the parser separately."""
        overrides = {key: value for key, value in ignores.items() if key != "globs"}
        unknown = set(overrides) - REPOSITORY_OVERRIDES
        if unknown:
            msg = f"unsupported repository guard overrides: {sorted(unknown)}"
            raise ValueError(msg)
        return self.model_validate({**self.model_dump(), **overrides})


# Settings keys a repository may override, next to ``ignores.globs``.
REPOSITORY_OVERRIDES = frozenset(
    {
        "include_globs",
        "exclude_migrations",
        "max_patch_bytes",
        "minified_line_length",
        "minified_avg_line_length",
    }
)


_LINGUIST_REASONS = {
    "linguist-generated": FileSkipReason.GENERATED,
    "linguist-vendored": FileSkipReason.VENDORED,
}


def _gitattributes_match(path: str, pattern: str) -> bool:
    """gitignore-style: a pattern with a slash is anchored at the repository root."""
    pure = PurePosixPath(path)
    if "/" in pattern.rstrip("/"):
        return pure.full_match(pattern.lstrip("/"))
    return pure.match(pattern)


def _linguist_reason(policy: InputGuardPolicy, path: str) -> FileSkipReason | None:
    state: dict[str, bool] = {}
    for pattern, name, is_set in policy.linguist_rules:  # the last match wins
        if _gitattributes_match(path, pattern):
            state[name] = is_set
    for name, reason in _LINGUIST_REASONS.items():
        if state.get(name):
            return reason
    return None


def matches_any(path: str, patterns: Iterable[str]) -> bool:
    """A slash-free pattern matches the file name at any depth; others any prefix."""
    pure = PurePosixPath(path)
    for pattern in patterns:
        if "/" not in pattern:
            if pure.match(pattern):
                return True
        elif pure.full_match(pattern) or pure.full_match(f"**/{pattern}"):
            return True
    return False


def metadata_reason(
    policy: InputGuardPolicy,
    *,
    is_deleted: bool,
    is_pure_rename: bool,
    is_binary: bool,
    patch_bytes: int,
) -> FileSkipReason | None:
    """Skip decided by diff metadata alone."""
    if is_deleted:
        return FileSkipReason.REMOVED
    if is_pure_rename:
        return FileSkipReason.PURE_RENAME
    if is_binary:
        return FileSkipReason.BINARY
    if patch_bytes > policy.max_patch_bytes:
        return FileSkipReason.TOO_LARGE
    return None


def path_reason(
    policy: InputGuardPolicy, path: str, ignore_globs: Iterable[str] = ()
) -> FileSkipReason | None:
    """Skip decided by the path; repository excludes win over includes."""
    if any(PurePosixPath(path).full_match(glob) for glob in ignore_globs):
        return FileSkipReason.IGNORED
    if matches_any(path, policy.include_globs):
        return None
    if linguist := _linguist_reason(policy, path):
        return linguist
    rules = (
        (policy.lockfile_globs, FileSkipReason.LOCKFILE),
        (
            policy.migration_globs if policy.exclude_migrations else (),
            FileSkipReason.MIGRATION,
        ),
        (policy.generated_globs, FileSkipReason.GENERATED),
        (policy.vendored_globs, FileSkipReason.VENDORED),
        (policy.bundle_globs, FileSkipReason.BUNDLE),
    )
    for patterns, reason in rules:
        if matches_any(path, patterns):
            return reason
    if PurePosixPath(path).suffix.lower() in policy.binary_extensions:
        return FileSkipReason.BINARY
    return None


def content_reason(
    policy: InputGuardPolicy, path: str, hunks: list[dict[str, Any]]
) -> FileSkipReason | None:
    """Skip decided by the diff text; included paths keep only the binary check."""
    added = [
        line["text"]
        for hunk in hunks
        for line in hunk["lines"]
        if line["kind"] == "added"
    ]
    probe = "\n".join(added).encode("utf-8")[: policy.content_probe_bytes]
    if b"\x00" in probe:
        return FileSkipReason.BINARY
    if matches_any(path, policy.include_globs):
        return None
    # Reviewed migrations often carry a framework "Generated by" header.
    reviewed_migration = not policy.exclude_migrations and matches_any(
        path, policy.migration_globs
    )
    if not reviewed_migration and _has_generated_marker(policy, hunks):
        return FileSkipReason.GENERATED
    if added and (
        _is_minified(policy, "".join(added), lines=len(added))
        or any(_is_minified(policy, text) for text in added)
    ):
        return FileSkipReason.MINIFIED
    return None


def _has_generated_marker(
    policy: InputGuardPolicy, hunks: list[dict[str, Any]]
) -> bool:
    return any(
        marker in line["text"].lower()
        for hunk in hunks
        for line in hunk["lines"]
        if line["new_line"] is not None
        and line["new_line"] <= policy.generated_header_lines
        and line["text"].lstrip().startswith(_COMMENT_PREFIXES)
        for marker in policy.generated_markers
    )


def _is_minified(policy: InputGuardPolicy, text: str, *, lines: int = 1) -> bool:
    """Minified text is long per line and has almost no whitespace.

    ``lines=1`` checks one line against the single-line threshold; more lines
    check their joined text against the average-length threshold.
    """
    limit = (
        policy.minified_line_length if lines == 1 else policy.minified_avg_line_length
    )
    whitespace = sum(1 for char in text if char.isspace())
    return (
        len(text) / lines > limit
        and whitespace <= len(text) * policy.minified_max_whitespace_ratio
    )
